#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { z } from "zod";

import {
  REGISTRY_VERSION,
  ROUTES,
} from "../packages/control-api/index.ts";

const root = resolve(new URL("..", import.meta.url).pathname);
const routesPath = resolve(root, "packages/control-sdk/routes.generated.ts");
const openapiPath = resolve(root, "packages/control-sdk/openapi.generated.json");
const browserTemplatePath = resolve(root, "scripts/m2-browser-sdk.template.js");
const browserPath = resolve(root, "packages/control-sdk/browser.generated.js");

const name = (routeId) =>
  routeId.replace(/\.([a-z])/g, (_match, letter) => letter.toUpperCase());
const routeLines = ROUTES.map(
  (route) =>
    `  ${JSON.stringify(name(route.routeId))}: { routeId: ${JSON.stringify(
      route.routeId,
    )}, method: ${JSON.stringify(route.method)}, pathTemplate: ${JSON.stringify(
      route.pathTemplate,
    )} },`,
).join("\n");
const routesSource = `// GENERATED by scripts/generate-m2-contracts.mjs — DO NOT EDIT.\nexport const GENERATED_REGISTRY_VERSION = ${JSON.stringify(
  REGISTRY_VERSION,
)} as const;\nexport const GENERATED_ROUTES = {\n${routeLines}\n} as const;\n`;

const successStatus = {
  "auth.session": "204",
  "agents.list": "200",
  "releases.list": "200",
  "intent.submit": "201",
  "runs.read": "200",
  "runs.events": "200",
  "runs.cancel": "202",
  "approvals.decide": "200",
  "health.read": "200",
};
const paths = {};
for (const route of ROUTES) {
  const path = route.pathTemplate.replace(/:([A-Za-z0-9_]+)/g, "{$1}");
  const operation = {
    operationId: route.routeId,
    security:
      route.authMode === "auth-session"
        ? [{ bootstrapBearer: [] }]
        : [{ controlCredential: [] }],
    parameters: [
      ...[...route.pathTemplate.matchAll(/:([A-Za-z0-9_]+)/g)].map(
        (match) => ({
          name: match[1],
          in: "path",
          required: true,
          schema: { type: "string" },
        }),
      ),
    ],
    responses: {
      [successStatus[route.routeId]]: route.routeId === "runs.events"
        ? {
            description: "Committed sanitized run events",
            content: { "text/event-stream": { schema: { type: "string" } } },
          }
        : route.routeId === "auth.session"
          ? { description: "Session cookie header block" }
          : {
              description: "Success",
              content: {
                "application/json": {
                  schema: route.responseSchema
                    ? z.toJSONSchema(route.responseSchema)
                    : {},
                },
              },
            },
      default: {
        description: "Typed error",
        content: {
          "application/json": {
            schema: {
              type: "object",
              additionalProperties: false,
              required: ["error"],
              properties: {
                error: {
                  type: "object",
                  additionalProperties: false,
                  required: ["schemaVersion", "kind", "message"],
                  properties: {
                    schemaVersion: { const: "wire-error-v1" },
                    kind: { type: "string" },
                    message: { type: "string" },
                  },
                },
              },
            },
          },
        },
      },
    },
  };
  if (route.bodySchema)
    operation.requestBody = {
      required: true,
      content: {
        "application/json": { schema: z.toJSONSchema(route.bodySchema) },
      },
    };
  paths[path] ??= {};
  paths[path][route.method.toLowerCase()] = operation;
}
const openapi = `${JSON.stringify(
  {
    openapi: "3.1.0",
    info: { title: "Hangar Control API", version: REGISTRY_VERSION },
    paths,
    components: {
      securitySchemes: {
        controlCredential: { type: "http", scheme: "bearer" },
        bootstrapBearer: { type: "http", scheme: "bearer" },
      },
    },
  },
  null,
  2,
)}\n`;

const browserSource = `// GENERATED by scripts/generate-m2-contracts.mjs — DO NOT EDIT.\n// registry: ${REGISTRY_VERSION}\n${readFileSync(browserTemplatePath, "utf8")}`;
const outputs = [
  [routesPath, routesSource],
  [openapiPath, openapi],
  [browserPath, browserSource],
];
if (process.argv.includes("--check")) {
  let clean = true;
  for (const [path, expected] of outputs) {
    let actual = "";
    try {
      actual = readFileSync(path, "utf8");
    } catch {
      clean = false;
      console.error(`missing generated artifact: ${path}`);
      continue;
    }
    if (actual !== expected) {
      clean = false;
      console.error(`generated artifact drift: ${path}`);
    }
  }
  if (clean) console.log("m2 generated contracts: clean"); else process.exitCode = 1;
} else {
  for (const [path, contents] of outputs) writeFileSync(path, contents);
  console.log("m2 generated contracts: written");
}
